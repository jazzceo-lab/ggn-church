alter table daily_verses enable row level security;

drop policy if exists "daily_verses_select_all" on daily_verses;
create policy "daily_verses_select_all"
on daily_verses for select
using (true);

drop policy if exists "daily_verses_admin_write" on daily_verses;
create policy "daily_verses_admin_write"
on daily_verses for all
using (exists (select 1 from profiles p where p.id = auth.uid() and p.is_admin = true))
with check (exists (select 1 from profiles p where p.id = auth.uid() and p.is_admin = true));

-- 주보. 예배순서/교회소식/기도제목/섬김이/표어처럼 항목이 여러 개인 부분은 기존 페이지
-- 컴포넌트가 그대로 읽을 수 있도록 jsonb 하나(content)에 같은 모양으로 넣어둔다.
create table if not exists bulletins (
  id bigint generated by default as identity primary key,
  issue text not null,
  bulletin_date date not null,
  content jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists bulletins_date_idx on bulletins (bulletin_date desc);

alter table bulletins enable row level security;

drop policy if exists "bulletins_select_all" on bulletins;
create policy "bulletins_select_all"
on bulletins for select
using (true);

drop policy if exists "bulletins_admin_write" on bulletins;
create policy "bulletins_admin_write"
on bulletins for all
using (exists (select 1 from profiles p where p.id = auth.uid() and p.is_admin = true))
with check (exists (select 1 from profiles p where p.id = auth.uid() and p.is_admin = true));
